export const USD_TO_ETB_RATE = 125.0; // 1 USD = 125 ETB approx

export function formatCurrency(amountInUsd: number, mode: CurrencyMode): string {
  if (mode === 'ETB') {
    const etb = amountInUsd * USD_TO_ETB_RATE;
    return `${Math.round(etb).toLocaleString()} ብር`;
  }
  return `$${amountInUsd.toLocaleString()}`;
}
